#!/usr/bin/env python3
"""Generate docs/INDEX.md: every large Markdown file's sections with their line ranges.

Sessions open one section by its line range (Read with offset and limit) instead of reading
or searching a whole document. `--check` exits 1 when docs/INDEX.md is stale, so
scripts/check.sh and the backend tests fail until it is regenerated.

Usage: python3 scripts/doc_index.py [--check]
Standard library only.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "docs" / "INDEX.md"
MIN_BYTES = 20_000  # "large": a file worth opening by section rather than whole
MAX_LEVEL = 3  # index ## and ### headings (# is the title)
SKIP_PREFIXES = ("frontend/node_modules/", "docs/journal/")
ARCHIVES = {"docs/AUTOPILOT_JOURNAL.md"}  # kept for history; nobody reads it


def tracked_markdown() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "*.md"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return sorted(
        {
            p
            for p in out.splitlines()
            if not p.startswith(SKIP_PREFIXES)
            and p not in ARCHIVES
            and p != "docs/INDEX.md"
            and (ROOT / p).is_file()
            and (ROOT / p).stat().st_size >= MIN_BYTES
        }
    )


def sections(lines: list[str]) -> list[tuple[int, str, int, int]]:
    """(level, title, first line, last line), 1-based and inclusive; skips fenced code."""
    heads: list[tuple[int, str, int]] = []
    fence = ""  # the opening fence (```, ````, ~~~ ...) while inside a code block
    for i, raw in enumerate(lines, start=1):
        line = raw.rstrip("\r")
        stripped = line.lstrip()
        marker = stripped[: len(stripped) - len(stripped.lstrip(stripped[:1]))]
        if stripped[:1] in "`~" and len(marker) >= 3:
            if not fence:
                fence = marker
            elif (
                marker[0] == fence[0]
                and len(marker) >= len(fence)
                and not stripped[len(marker) :].strip()
            ):
                fence = ""
            continue
        if fence or not line.startswith("#"):
            continue
        level = len(line) - len(line.lstrip("#"))
        if 2 <= level <= MAX_LEVEL and line[level : level + 1] == " ":
            title = line[level + 1 :].strip().rstrip("#").strip()
            heads.append((level, title, i))
    result = []
    for k, (level, title, start) in enumerate(heads):
        end = len(lines)
        for later_level, _, later_start in heads[k + 1 :]:
            if later_level <= level:
                end = later_start - 1
                break
        result.append((level, title, start, end))
    return result


def render() -> str:
    out = [
        "# Documentation index (generated)",
        "",
        "Generated by `scripts/doc_index.py`; do not edit by hand (`scripts/check.sh` fails when",
        "it is stale). Every Markdown file of 20 KB or more (not the closed journal archive or",
        "`docs/journal/`), with its `##` and `###` sections and their line ranges. Open one",
        "section with Read's offset and limit (offset = first line, limit = last - first + 1)",
        "instead of reading or searching the whole file.",
        "",
    ]
    for path in tracked_markdown():
        text = (ROOT / path).read_text(encoding="utf-8").splitlines()
        out.append(f"## `{path}` ({len(text)} lines)")
        for level, title, start, end in sections(text):
            indent = "  " * (level - 2)
            out.append(f"{indent}- {start}-{end}: {title}")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != content:
            print("docs/INDEX.md is stale: run python3 scripts/doc_index.py", file=sys.stderr)
            return 1
        return 0
    INDEX.write_text(content, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
