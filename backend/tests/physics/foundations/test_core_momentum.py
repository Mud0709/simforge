"""Tests for momentum(m, v): the first function you write (sitting 0).

What this checks: momentum = mass x velocity (p = m v), in kg m/s. Every expected value
below was worked out by hand, not taken from the code. A negative velocity means the
body moves the other way, so its momentum is negative too; zero velocity gives zero.

How to run it (from the repository folder):
    cd backend
    uv run pytest tests/physics/foundations/test_core_momentum.py -q

Red (failing) means momentum is not written yet; green (passing) means it is right.
Do not edit this file: change core.py until the test passes.
"""

import pytest

from simforge.physics.foundations.collisions.core import momentum
from tests.approx import rel_approx

# Tolerance: every mass and velocity here is a whole number or a half, so m * v is
# stored exactly in a float; 1e-12 allows harmless rounding yet catches any wrong formula.
REL = 1e-12


@pytest.mark.parametrize(
    ("m", "v", "expected"),
    [
        (2.0, 3.0, 6.0),  # 2 x 3 = 6
        (1.0, 1.0, 1.0),  # 1 x 1 = 1
        (1.5, 4.0, 6.0),  # 1.5 x 4 = 6
        (2.5, 0.5, 1.25),  # 2.5 x 0.5 = 1.25
        (3.0, -2.0, -6.0),  # moving the other way: 3 x (-2) = -6
        (4.0, 0.0, 0.0),  # at rest: 4 x 0 = 0 (a relative tolerance at 0 means exactly 0)
    ],
    ids=[
        "2kg_at_3m_per_s",
        "1kg_at_1m_per_s",
        "1.5kg_at_4m_per_s",
        "2.5kg_at_0.5m_per_s",
        "3kg_at_minus_2m_per_s_backwards",
        "4kg_at_rest",
    ],
)
def test_momentum_is_mass_times_velocity(m: float, v: float, expected: float) -> None:
    result = momentum(m, v)
    assert result == rel_approx(expected, REL), (
        f"momentum({m}, {v}) should be {expected} kg m/s (mass times velocity), got {result}"
    )
